import assert from 'node:assert/strict';
import {parseTeamPersonnel,matchupPersonnel} from '../lib/team-personnel.mjs';
const now=Date.now(),at=new Date(now).toISOString();
const payload={season:{year:2026},team:{abbreviation:'WSH'},timestamp:at,athletes:[{position:'defense',items:[{id:'1',displayName:'Defender',position:{abbreviation:'CB'},status:{name:'Active'}}]},{position:'offense',items:[{id:'2',displayName:'Lineman',position:{abbreviation:'OT'}}]}]};
const injury={athlete_id:'1',name:'Defender',status:'Out',source_updated_at:'2026-08-01T00:00:00Z'};
const roster=parseTeamPersonnel(payload,'WAS',[{athlete_id:'2',name:'Lineman',position:'LT',rank:2}],[injury],at,'test');
assert.equal(roster.players.length,2);
assert.equal(roster.players[0].injury_reports[0].source_updated_at,injury.source_updated_at);
assert.equal(roster.players[0].game_availability,'UNKNOWN');
assert.equal(roster.players[0].injury_reports[0].freshness_status,'REVIEW_REQUIRED');
assert.equal(roster.players[1].depth_roles[0].rank,2);
const snapshot={season:2026,week:2,sportsbook_inputs_used:false,teams:{WAS:roster,NYG:{...roster,team:'NYG'}}};
const game={home_team:'WSH',away_team:'NYG'};
assert.equal(matchupPersonnel(snapshot,game,2,now).status,'CONNECTED');
assert.equal(matchupPersonnel(snapshot,game,1,now).status,'UNAVAILABLE');
assert.equal(matchupPersonnel(snapshot,game,2,now+25*3600000).status,'REVIEW_REQUIRED');
assert.equal(matchupPersonnel({...snapshot,sportsbook_inputs_used:true},game,2,now).status,'UNAVAILABLE');
assert.equal(matchupPersonnel(snapshot,game,2,now).numeric_adjustment_applied,false);
assert.throws(()=>parseTeamPersonnel({...payload,season:{year:2025}},'WAS',[],[],at,'test'));
assert.throws(()=>parseTeamPersonnel(payload,'NYG',[],[],at,'test'));
console.log('PASS: linemen/defenders, identities, injury dates, depth roles, aliases, freshness and provenance');
