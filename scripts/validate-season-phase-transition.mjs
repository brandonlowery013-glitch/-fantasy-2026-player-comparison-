import fs from 'node:fs';
const cfg=JSON.parse(fs.readFileSync('data/sources/season-phase-2026.json','utf8'));
const blocked=[];
if(cfg.season!==2026)blocked.push('season must be 2026');
if(cfg.timezone!=='America/Chicago')blocked.push('timezone must match Chicago operating timezone');
if(cfg.football_state!=='REGULAR_SEASON_ACTIVE')blocked.push('football state must be REGULAR_SEASON_ACTIVE');
if(cfg.regular_season_mode?.active!==true)blocked.push('regular-season mode must already be active');
if(cfg.fantasy_draft_reference?.state_gate!==false)blocked.push('fantasy draft completion must never gate football state');
if(cfg.rules?.fantasy_draft_date_never_controls_football_state!==true)blocked.push('missing no-draft-date-state-gate rule');
const regular=new Set(cfg.regular_season_mode?.promote||[]);
for(const k of ['weekly_projection','actual_usage','snaps_routes_targets_touches','availability','rank_movement','news_context','waiver_roster_value'])if(!regular.has(k))blocked.push(`regular-season mode missing ${k}`);
const de=new Set(cfg.regular_season_mode?.deemphasize_but_preserve||[]);
for(const k of ['current_adp','preferred_draft_range','draft_round'])if(!de.has(k))blocked.push(`regular-season de-emphasis missing ${k}`);
if(cfg.rules?.rank_arrow_requires_actual_saved_rank_change!==true)blocked.push('rank arrows must require an actual saved rank change');
if(cfg.rules?.news_without_rank_change_shows_news_badge_only!==true)blocked.push('HOLD news must not create a false arrow');
const result={generated_at:new Date().toISOString(),result:blocked.length?'BLOCKED':'PASS',season:2026,football_state:cfg.football_state,fantasy_draft_state_gate:cfg.fantasy_draft_reference?.state_gate,policy:'ONE FOOTBALL HANDOFF ONLY: CAMP/PRESEASON TO REGULAR SEASON; USER FANTASY DRAFT DATE IS NEVER A MODEL STATE TRANSITION',blocked};
fs.mkdirSync('guardrails',{recursive:true});
fs.writeFileSync('guardrails/season-phase-transition-report.json',JSON.stringify(result,null,2)+'\n');
console.log(JSON.stringify(result,null,2));
if(blocked.length)process.exit(1);
