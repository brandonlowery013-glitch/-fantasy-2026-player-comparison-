import assert from 'node:assert/strict';
import {parseInjuryReports,assessInjury,resolveAvailability,injuryFreshness} from '../lib/injury-evidence.mjs';
import {parseTeamPersonnel,matchupPersonnel,weeklyInjurySummary} from '../lib/team-personnel.mjs';
const now=Date.parse('2026-09-16T12:00:00Z'),fresh='2026-09-16T10:00:00Z',old='2026-09-14T10:00:00Z';
const athlete={displayName:'Test QB',position:{abbreviation:'QB'},links:[{href:'https://www.espn.com/nfl/player/_/id/123/test-qb'}]};
const out={id:'999',athlete,status:'Out',date:fresh};
const parsed=parseInjuryReports([out]);
assert.equal(parsed[0].athlete_id,'123');assert.equal(parsed[0].report_id,'999');
assert.equal(assessInjury(parsed[0],now).expected_active,false);
assert.equal(parseInjuryReports([{...out,athlete:{...athlete,links:[{href:'https://evil.example/nfl/player/_/id/123/test-qb'}]}}])[0].athlete_id,null);
assert.equal(parseInjuryReports([{status:{name:'Active'},displayName:'Roster only'}]).length,0);
const newest=parseInjuryReports([{...out,status:'Active',date:old},out]);
assert.equal(newest[0].status,'Out');
assert.equal(parseInjuryReports([out,{...out,status:'Active',date:old}])[0].status,'Out');
const conflict=parseInjuryReports([out,{...out,status:'Active'}])[0];
assert.equal(assessInjury(conflict,now).expected_active,null);
assert.equal(injuryFreshness({source_updated_at:old,captured_at:fresh},now).status,'REVIEW_REQUIRED');
assert.equal(assessInjury({...parsed[0],source_updated_at:old},now).expected_active,null);
assert.equal(assessInjury({...parsed[0],source_updated_at:'2026-09-17T00:00:00Z'},now).expected_active,null);
assert.equal(assessInjury({...parsed[0],source_updated_at:null},now).expected_active,null);
const activeRole={captured_at:fresh,evidence:{espn_active_flag:true}};
assert.equal(resolveAvailability({role:activeRole},now).expected_active,true);
assert.equal(resolveAvailability({role:{...activeRole,captured_at:old}},now+3600000).expected_active,null);
for(const status of ['Out','Injured Reserve','Inactive','Suspended'])assert.equal(resolveAvailability({role:activeRole,injury:{evidence:{status,source_updated_at:fresh}}},now).expected_active,false);
for(const status of ['Questionable','Doubtful','UNKNOWN'])assert.equal(resolveAvailability({role:activeRole,injury:{expected_active:true,evidence:{status,practice_status:'Full Practice',source_updated_at:fresh}}},now).expected_active,null);
assert.equal(resolveAvailability({role:activeRole,injury:{expected_active:false,evidence:{status:'Out',source_updated_at:old}}},now).expected_active,null);
assert.equal(resolveAvailability({injury:{expected_active:false,evidence:{status:'Active',source_updated_at:fresh}}},now).expected_active,true);
assert.equal(resolveAvailability({injury:{evidence:{status:'Active',practice_status:'Limited',source_updated_at:fresh}}},now).expected_active,null);
const payload={season:{year:2026},team:{abbreviation:'MIN'},athletes:[{position:'offense',items:[{id:'123',displayName:'Test QB',position:{abbreviation:'QB'},status:{name:'Active'}}]}]};
const roster=parseTeamPersonnel(payload,'MIN',[{athlete_id:'123',position:'QB',rank:1}],parsed,fresh,'test');
assert.equal(roster.players[0].game_availability,'EXPECTED_INACTIVE');
const snapshot={season:2026,week:2,sportsbook_inputs_used:false,teams:{MIN:roster,CHI:{...roster,team:'CHI'}}};
const expired=matchupPersonnel(snapshot,{home_team:'MIN',away_team:'CHI'},2,now+13*3600000);
assert.equal(expired.teams.MIN.players[0].game_availability,'UNKNOWN');
assert.equal(expired.teams.MIN.availability_summary.unresolved_depth_leaders.length,1);
assert.equal(expired.numeric_adjustment_applied,false);
console.log('PASS: report identities, source-age expiry, refetch isolation, conflict/uncertainty precedence and roster expiry');

// Reported designation survives refresh age; long-term absences need a superseding report.
const retained=assessInjury({status:'Questionable',source_updated_at:old},now);
assert.equal(retained.reported_designation,'Questionable');assert.equal(retained.expected_active,null);
assert.equal(assessInjury({status:'Injured Reserve',source_updated_at:old},now).expected_active,false);
const summary=weeklyInjurySummary(expired.teams.MIN.players,{home_team:'MIN',away_team:'CHI'},2);
assert.equal(summary.week,2);assert.equal(summary.items[0].designation,'Out');
assert.equal(summary.items[0].reported_at,new Date(fresh).toISOString());assert.equal(summary.items[0].confirmed_for_game,false);
assert.equal(weeklyInjurySummary([{...expired.teams.MIN.players[0],latest_reported_status:'Active'}],{},2).items.length,0);
console.log('PASS: retained designations, long-term absences, weekly injury filtering and dated status');
