import assert from 'node:assert/strict';
import {parseEventDepth,leagueInjuriesByTeam} from '../lib/event-source-binding.mjs';
import {parseInjuryReports} from '../lib/injury-evidence.mjs';
import {weeklyRankStatus} from '../lib/weekly-ranking-availability.mjs';
const league={injuries:Array.from({length:32},(_,i)=>({id:String(i+1),injuries:[]}))};
league.injuries[20].injuries=[{athlete:{displayName:'Test RB',id:'123',position:{abbreviation:'RB'}},status:'Out',date:'2026-10-09T15:32Z'}];
assert.throws(()=>leagueInjuriesByTeam({}));
assert.throws(()=>leagueInjuriesByTeam({injuries:[league.injuries[20]]}));
const reports=parseInjuryReports(leagueInjuriesByTeam(league).get('21'));
assert.equal(reports.length,1);assert.equal(reports[0].athlete_id,'123');
const depth=parseEventDepth({depthchart:[{positions:{rb:{position:{abbreviation:'RB'},athletes:[{displayName:'Test RB'},{displayName:'Backup RB',rank:3}]}}}]});
assert.deepEqual(depth.map(p=>p.rank),[1,3]);
assert.equal(parseEventDepth({items:[{athletes:[{displayName:'Untyped'}]}]}).length,0);
const now=Date.parse('2026-10-11T15:00Z'),game={event_start:'2026-10-11T17:00Z'};
const context={expected_active:true,signals:{injury:{evidence:reports[0]}}};
assert.equal(weeklyRankStatus(context,game,now),'REPORTED_ABSENCE_REVIEW_REQUIRED');
assert.equal(weeklyRankStatus(context,{event_start:'2026-10-11T13:30Z'},now),'REPORTED_ABSENCE_REVIEW_REQUIRED');
context.signals.injury.evidence={...reports[0],source_updated_at:'2026-10-11T14:00Z'};
assert.equal(weeklyRankStatus(context,game,now),'NOT_EXPECTED_TO_PLAY');
context.signals.injury.evidence.status='Questionable';
assert.equal(weeklyRankStatus(context,game,now),'PROVISIONAL_AVAILABILITY_REVIEW');
context.signals.injury.evidence.status='Active';
assert.equal(weeklyRankStatus(context,game,now),'MODEL_RANK');
console.log('PASS: league injury binding, empty-schema rejection, array-order depth, stale OUT hold, uncertain and superseding availability');
