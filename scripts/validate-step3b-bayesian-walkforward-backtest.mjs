import fs from 'node:fs';
const p='guardrails/step3b-bayesian-walkforward-backtest.json';
if(!fs.existsSync(p))throw new Error('Missing Step 3B Bayesian backtest report');
const r=JSON.parse(fs.readFileSync(p,'utf8'));
const need=(ok,msg)=>{if(!ok)throw new Error(msg)};
need(r.status==='SHADOW_ONLY','Backtest must remain shadow-only');
need(r.live_weight===0&&r.live_projection_movement===0&&r.live_rank_movement===0,'Backtest may not grant live influence');
need(r.leakage_controls?.sportsbook_used===false,'Sportsbook contamination prohibited');
need(r.leakage_controls?.adp_used===false,'ADP contamination prohibited');
need(r.leakage_controls?.current_2026_outcomes_used===false,'2026 outcomes cannot leak into held-out backtest');
need(r.leakage_controls?.prior_rows_must_precede_target_season===true,'Walk-forward chronology required');
need(r.tuning?.training_examples>=20,'Training sample too small');
need(r.holdout?.examples>=30,'Holdout sample too small');
need(Number.isFinite(r.tuning?.selected_k_pseudogames)&&r.tuning.selected_k_pseudogames>0,'Empirically selected shrinkage k missing');
need(Number.isFinite(r.holdout?.baseline?.mae)&&Number.isFinite(r.holdout?.bayes?.mae),'MAE missing');
need(Number.isFinite(r.holdout?.baseline?.rmse)&&Number.isFinite(r.holdout?.bayes?.rmse),'RMSE missing');
need(['MEAN_SHRINKAGE_SIGNAL_PASSES_PHASE1','NO_PROMOTION_SIGNAL'].includes(r.conclusion),'Invalid Phase 1 conclusion');
need(r.promotion_status==='BLOCKED_PENDING_DISTRIBUTION_CALIBRATION_AND_USER_REVIEW','Promotion must stay blocked after Phase 1');
console.log(`Step 3B Bayesian walk-forward validation PASS — ${r.conclusion}`);
